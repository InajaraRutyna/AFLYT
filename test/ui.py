"""UI playthrough on a phone-sized screen. Run: python3 test/ui.py [outdir]"""
import pathlib, sys
from playwright.sync_api import sync_playwright
root = pathlib.Path(__file__).resolve().parent.parent
out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/aflyt-shots"); out.mkdir(parents=True, exist_ok=True)
errs = []
def wait_debrief(pg):
    pg.wait_for_selector("#b-skip:not([hidden])", timeout=5000); pg.click("#b-skip")
    pg.wait_for_selector("#sheet:not([hidden]) .stamp", timeout=30000)
    return pg.inner_text(".stamp")
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 390, "height": 844}, device_scale_factor=2, has_touch=True)
    pg.on("pageerror", lambda e: errs.append("pageerror " + str(e)))
    pg.on("console", lambda m: m.type == "error" and errs.append("console " + m.text))
    pg.goto((root / "index.html").as_uri()); pg.wait_for_timeout(500)
    pg.screenshot(path=str(out / "0-menu.png"))
    pg.click(".ncard[data-n='1']"); pg.wait_for_timeout(300)
    pg.screenshot(path=str(out / "1-night1.png"))
    pg.click(".play[data-k='0']"); pg.wait_for_timeout(1500)
    pg.click("#tab-orders"); pg.wait_for_timeout(200)
    pg.screenshot(path=str(out / "2-orders.png"))
    pg.click("#b-run"); pg.wait_for_timeout(1800); pg.screenshot(path=str(out / "3-running.png"))
    r1 = wait_debrief(pg); pg.wait_for_timeout(400); pg.screenshot(path=str(out / "4-debrief-draft.png"), full_page=False)
    print("draft run:", r1)
    pg.click("#d-rew"); pg.wait_for_timeout(300)
    pg.fill("#ord-0", "Om to minutter går Ida til posthuset for at hente nøglen.")
    pg.fill("#ord-1", "Derefter går hun tilbage til bilen.")
    # board tap inserts a word into the active line
    box = pg.query_selector("#board").bounding_box()
    pg.click("#board", position={"x": box["width"] * 286 / 360, "y": box["height"] * 60 / 300}); pg.wait_for_timeout(200)
    print("after tap:", pg.input_value("#ord-1"))
    pg.fill("#ord-1", "Derefter går hun tilbage til bilen.")
    print("lines:", pg.evaluate("()=>window.AFLYT.G.lines.map(l=>l.text)"))
    pg.click("#b-run"); r2 = wait_debrief(pg); pg.wait_for_timeout(400)
    pg.screenshot(path=str(out / "5-debrief-win.png")); print("solution run:", r2)
    pg.click("#d-next"); pg.wait_for_timeout(300); pg.screenshot(path=str(out / "6-night2.png"))
    N2 = pg.evaluate("()=>window.AFLYT.G.N.solution")
    pg.click("#tab-orders"); pg.fill("#ord-0", N2[0]); pg.fill("#ord-1", N2[1])
    pg.click("#b-run"); print("night 2:", wait_debrief(pg))
    pg.click("#d-next"); pg.wait_for_timeout(300); pg.screenshot(path=str(out / "7-night3.png"))
    pg.click("#tab-orders"); pg.fill("#ord-0", "Når vagten går, går Ida til caféen for at hente nøglen."); pg.fill("#ord-1", "Derefter går hun tilbage til bilen.")
    pg.click("#b-run"); print("night 3:", wait_debrief(pg)); pg.screenshot(path=str(out / "8-night3-debrief.png"))
    pg.click("#d-menu"); pg.wait_for_timeout(300); pg.screenshot(path=str(out / "9-menu-after.png"))
    pg.click("#m-form"); pg.wait_for_timeout(200); pg.screenshot(path=str(out / "10-form.png"))
    sw = pg.evaluate("()=>document.documentElement.scrollWidth"); print("scrollWidth", sw)
    b.close()
print("ERRORS", errs)
sys.exit(1 if errs else 0)
